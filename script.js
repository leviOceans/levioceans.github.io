function typeTitle() {
    if (!titleElement || !cursor) {
        return;
    }

    if (i < titleText.length) {
        titleElement.textContent += titleText.charAt(i);
        i++;
        setTimeout(typeTitle, 50);
    } else {
        // remove cursor após digitar
        // DEPOIS
        setTimeout(() => {
            cursor.style.animation = "none";
            cursor.style.visibility = "hidden";
        }, 500);

        // mostra a bio
        showBio();
    }
}

if (titleElement && cursor) {
    typeTitle();
}

