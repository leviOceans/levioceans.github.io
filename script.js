function getLanguage() {
    // Detecta diretamente o idioma do navegador
    const browserLang = (navigator.language || navigator.userLanguage || "en").toLowerCase();
    
    // Mapeia linguagens do navegador para as disponíveis
    if (browserLang.startsWith("pt")) {
        return "pt-br";
    } else if (browserLang.startsWith("es")) {
        return "es";
    } else if (browserLang.startsWith("nl")) {
        return "nl";
    } else {
        return "en";
    }
}

function setLanguage(lang) {
    document.documentElement.setAttribute("lang", lang);
    applyTranslations(lang);
}

function applyTranslations(lang) {
    const translations = i18n[lang] || i18n["pt-br"];
    
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        // Skip translation if element has keep-pt-br class and target language is not pt-br
        if (el.classList.contains("keep-pt-br") && lang !== "pt-br") {
            return;
        }
        if (translations[key]) {
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.placeholder = translations[key];
            } else {
                el.innerHTML = translations[key];
            }
        }
    });
}

